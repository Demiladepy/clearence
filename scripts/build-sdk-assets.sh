#!/usr/bin/env bash
# Rebuild everything the TypeScript SDK ships, from source:
#   packages/sdk/src/wasm/       clearance-wasm (Rust -> wasm32) + wasm-bindgen JS
#   packages/sdk/src/vendor/     circom's witness calculator for clearance_tx_2_2, as ESM
#   packages/sdk/artifacts/      circuit WASM, R1CS, proving key, VK + SHA256SUMS
# Needs `make circuits` first (artifacts and keys) and wasm-bindgen 0.2.128.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UP="$ROOT/upstream/nethermind-spp"
SDK="$ROOT/packages/sdk"
"$ROOT/scripts/sync-upstream.sh" >/dev/null
(cd "$UP" && cargo build -p clearance-wasm --target wasm32-unknown-unknown --release)
wasm-bindgen --target web --out-dir "$SDK/src/wasm" --out-name clearance_wasm \
  "$UP/target/wasm32-unknown-unknown/release/clearance_wasm.wasm"
{
  echo "// Generated by circom for clearance_tx_2_2 (target/circuits-artifacts/out/wasm/clearance_tx_2_2_js),"
  echo "// with two edits for ES modules (strict mode): \`module.exports =\` -> \`export default\`,"
  echo "// and \`a = flatArray(input)\` -> \`const a = ...\` (an undeclared assignment). See scripts/build-sdk-assets.sh."
  sed -e 's/^module.exports = async function builder(code, options) {/export default async function builder(code, options) {/' \
      -e 's/^\ta = flatArray(input);$/\tconst a = flatArray(input);/' \
      "$UP/target/circuits-artifacts/out/wasm/clearance_tx_2_2_js/witness_calculator.js"
} > "$SDK/src/vendor/witness_calculator.js"
mkdir -p "$SDK/artifacts"
cp "$UP/target/circuits-artifacts/out/wasm/clearance_tx_2_2_js/clearance_tx_2_2.wasm" \
   "$UP/target/circuits-artifacts/clearance_tx_2_2.r1cs" \
   "$UP/testdata/clearance_tx_2_2_proving_key.bin" "$UP/testdata/clearance_tx_2_2_vk.json" "$SDK/artifacts/"
(cd "$SDK/artifacts" && sha256sum clearance_tx_2_2.r1cs clearance_tx_2_2.wasm clearance_tx_2_2_proving_key.bin clearance_tx_2_2_vk.json > SHA256SUMS)
echo "SDK assets rebuilt"
