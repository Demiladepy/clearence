#!/usr/bin/env bash
# Writes docs/evidence/README.md from the last `make test` log and the compiled
# circuits. Numbers here are generated, never typed by hand.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UP="$ROOT/upstream/nethermind-spp"
ART="$UP/target/circuits-artifacts"
OUT="$ROOT/docs/evidence/README.md"
LOG="$ROOT/docs/evidence/test-run.log"
r1cs() { for n in "$@"; do f="$ART/$n.r1cs"; [ -f "$f" ] || f="$ART/out/$n.r1cs"; echo "$f"; done; }

{
  echo "# Evidence"
  echo
  echo "Generated by \`make verify\` on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit by hand."
  echo
  echo "- Clearance commit: \`$(git -C "$ROOT" rev-parse --short HEAD)\`$(git -C "$ROOT" diff --quiet HEAD -- . ':!docs/evidence' || echo ' (plus uncommitted changes)')"
  echo "- Upstream (Nethermind SPP): \`$(git -C "$UP" rev-parse --short HEAD)\`"
  echo "- Machine: $(nproc) vCPU, $(uname -s) $(uname -m)"
  echo
  echo "## Tests"
  echo
  echo '```'
  grep -E '^test .* \.\.\. |^test result:' "$LOG" | sed 's/^test test::/test /'
  echo '```'
  echo
  echo "Full log: [test-run.log](test-run.log)."
  echo
  echo "## Circuit size"
  echo
  echo "Clearance circuits (test harness entry points):"
  echo
  python3 "$ROOT/scripts/r1cs-info.py" $(r1cs pack_hash_test clearance_identity_test clearance_budget_test clearance_tx_2_2)
  echo
  echo "## Pool cost on Soroban (measured by clearance-e2e, real proofs)"
  echo
  cat "$UP/target/clearance-pool-costs.md" 2>/dev/null || echo "(not measured: run make test-e2e)"
  echo
  echo "Upstream baselines we extend:"
  echo
  python3 "$ROOT/scripts/r1cs-info.py" $(r1cs policy_tx_2_2 policy_tx_2_2_A policy_tx_2_2_A_gvk_V)
} > "$OUT"
if grep -q "FAILED\|test result: FAILED" "$LOG"; then echo "evidence written, but tests FAILED: see $LOG" >&2; exit 1; fi
echo "wrote $OUT"
